echo "📊 Session: ${SESSION_ID}"
echo "🔢 Sections: ${total} + scoring"
echo ""
echo "Next steps:"
echo "  1. Review report in ${REPORT_FILE}"
echo "  2. Copy to /mnt/user-data/outputs/ for download"
